<?php
$num1 = 50;
$num2 = 30;


$isGreater = $num1 > $num2;  
$isEqual = $num1 == $num2;   
$isNotEqual = $num1 != $num2; 


echo "num1 > num2: " . ($isGreater ? "true" : "false") . "\n";
echo "num1 == num2: " . ($isEqual ? "true" : "false") . "\n";
echo "num1 != num2: " . ($isNotEqual ? "true" : "false") . "\n";
?>
